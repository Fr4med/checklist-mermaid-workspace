import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { packageDiagram } from './package-diagram.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
await mkdir('dist', { recursive: true });
await mkdir('src', { recursive: true });
await build({entryPoints:['public/app.js','public/mermaid.js'], bundle:true, minify:true, format:'esm', target:'es2022', outdir:'dist', legalComments:'none'});
const assets = {};
for (const [path, file, contentType] of [
  ['/','public/index.html','text/html; charset=utf-8'],
  ['/styles.css','public/styles.css','text/css; charset=utf-8'],
  ['/app.js','dist/app.js','text/javascript; charset=utf-8'],
  ['/favicon.svg','public/favicon.svg','image/svg+xml'],
  ['/mermaid','public/mermaid.html','text/html; charset=utf-8'],
  ['/mermaid.css','public/mermaid.css','text/css; charset=utf-8'],
  ['/mermaid.js','dist/mermaid.js','text/javascript; charset=utf-8'],
]) {
  const body = await readFile(file, 'utf8');
  assets[path] = {body: path === '/styles.css' ? `${body}\n${await readFile('public/selection.css','utf8')}` : body, contentType};
}
const diagram = process.env.INTERACTIVE_DIAGRAM_FILE ? await packageDiagram(process.env.INTERACTIVE_DIAGRAM_FILE) : null;
await writeFile('src/assets.mjs', `// Generated by scripts/build.mjs.\nexport const assets = ${JSON.stringify(assets)};\nexport const interactiveDiagram = ${JSON.stringify(diagram)};\n`);
console.log(diagram ? `Packaged optional interactive diagram (${diagram.sha256}).` : 'No optional interactive diagram configured; the SVG workspace remains available.');
try {
  await readFile('src/worker.mjs');
  await build({entryPoints:['src/worker.mjs'], bundle:true, minify:true, format:'esm', platform:'browser', target:'es2022', outfile:'dist/worker.mjs', legalComments:'none'});
  console.log('Built browser assets and Cloudflare Worker.');
} catch (e) { if (e.code === 'ENOENT') console.log('Built browser assets; Worker implementation pending.'); else throw e; }
